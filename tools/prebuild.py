"""PlatformIO pre-build step: embed the gzipped web UI and the version.

Writes src/generated/web_assets.h and src/generated/version.h. The version is
GAUGECAM_VERSION when set (CI), else `git describe`, else "dev".
"""
import gzip
import os
import subprocess

try:
    Import("env")  # noqa: F821  (PlatformIO SCons environment)
    ROOT = env["PROJECT_DIR"]  # noqa: F821
except NameError:  # run by hand
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "src", "generated")
TYPES = {".html": "text/html", ".js": "application/javascript", ".css": "text/css",
         ".svg": "image/svg+xml"}


def version():
    if os.environ.get("GAUGECAM_VERSION"):
        return os.environ["GAUGECAM_VERSION"]
    try:
        return subprocess.check_output(
            ["git", "describe", "--tags", "--always", "--dirty"], cwd=ROOT,
            stderr=subprocess.DEVNULL, text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return "dev"


def write_if_changed(path, text):
    if os.path.exists(path) and open(path).read() == text:
        return
    with open(path, "w") as handle:
        handle.write(text)


def main():
    os.makedirs(OUT, exist_ok=True)
    lines = ["// Generated by tools/prebuild.py, do not edit.", "#pragma once",
             "#include <stddef.h>", "#include <stdint.h>", ""]
    entries = []
    for name in sorted(os.listdir(WEB)):
        ext = os.path.splitext(name)[1]
        if ext not in TYPES:
            continue
        data = gzip.compress(open(os.path.join(WEB, name), "rb").read(), 9, mtime=0)
        ident = "asset_" + "".join(c if c.isalnum() else "_" for c in name)
        body = ",".join(str(b) for b in data)
        lines.append(f"static const uint8_t {ident}[] = {{{body}}};")
        entries.append(f'  {{"/{name}", "{TYPES[ext]}", {ident}, sizeof({ident})}},')
    lines += ["", "struct WebAsset { const char* path; const char* type; const uint8_t* data; size_t size; };",
              "static const WebAsset kWebAssets[] = {", *entries, "};", ""]
    write_if_changed(os.path.join(OUT, "web_assets.h"), "\n".join(lines))
    write_if_changed(os.path.join(OUT, "version.h"),
                     f'// Generated by tools/prebuild.py.\n#pragma once\n#define GAUGECAM_VERSION "{version()}"\n')


main()
